export function vehicleNameKey(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");
}

function pick(entry: LocalizedName | undefined, locale: Locale): string | undefined {
  if (!entry) return undefined;
  return entry[locale] || entry.en;
}

function lookup(
  table: Record<string, LocalizedName>,
  value: string,
  locale: Locale,
): string | undefined {
  const raw = value.trim();
  if (!raw) return undefined;
  const key = vehicleNameKey(raw);
  const direct = pick(table[key] ?? table[raw.toLowerCase()], locale);
  if (direct) return direct;
  if (key.includes("_")) {
    const tail = key.split("_").slice(1).join("_");
    const fromTail = pick(table[tail], locale);
    if (fromTail) return fromTail;
  }
  return undefined;
}

export function localizeBrandName(value: string, locale: Locale): string {
  return lookup(VEHICLE_BRANDS, value, locale) ?? value;
}

export function localizeModelName(value: string, locale: Locale): string {
  return lookup(VEHICLE_MODELS, value, locale) ?? value;
}

export function localizeTrimName(value: string, locale: Locale): string {
  return lookup(VEHICLE_TRIMS, value, locale) ?? value;
}
