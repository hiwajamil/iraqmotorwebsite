const dict: Record<Locale, Record<DictKey, string>> = { en, ar, ku };

export function t(
  locale: Locale,
  key: DictKey,
  vars?: Record<string, string | number>,
) {
  let value = dict[locale][key] ?? dict.en[key];
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
  }
  return value;
}

const LISTING_STATUS_KEYS: Record<string, DictKey> = {
  active: "statusActive",
  pending: "statusPending",
  draft: "statusDraft",
  rejected: "statusRejected",
  sold: "sold",
  expired: "statusExpired",
  banned: "statusBanned",
  inactive: "statusInactive",
};

export function listingStatusLabel(
  locale: Locale,
  status?: string | null,
): string {
  const s = (status || "draft").toLowerCase();
  return t(locale, LISTING_STATUS_KEYS[s] ?? "statusDraft");
}

export function accountTypeLabel(
  locale: Locale,
  type?: string | null,
): string {
  const s = (type || "").toLowerCase();
  if (s === "showroom") return t(locale, "accountTypeShowroom");
  if (s === "individual") return t(locale, "accountTypeIndividual");
  return type?.trim() || "";
}

const LEAD_STATUS_KEYS: Record<string, DictKey> = {
  new: "leadStatusNew",
  contacted: "leadStatusContacted",
  resolved: "leadStatusResolved",
};

export function leadStatusLabel(
  locale: Locale,
  status?: string | null,
): string {
  const s = (status || "").toLowerCase();
  return LEAD_STATUS_KEYS[s] ? t(locale, LEAD_STATUS_KEYS[s]) : status || "";
}

export function isRtl(locale: Locale) {
  return locale === "ar" || locale === "ku";
}

